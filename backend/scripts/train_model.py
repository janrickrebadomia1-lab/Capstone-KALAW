import os,pickle,math,re
from collections import Counter,defaultdict
from langchain_chroma import Chroma

os.environ["ANONYMIZED_TELEMETRY"]="False"

BASE_DIR=os.path.dirname(os.path.abspath(__file__))
DATA_DIR=os.path.join(BASE_DIR,"..","data")
CHROMA_PATH=os.path.join(DATA_DIR,"chroma_db")
OUT_PATH=os.path.join(DATA_DIR,"tfidf_embeddings.pkl")

def tokenize(text:str)->list[str]:
    return re.findall(r"[a-z0-9]+", text.lower())

def build_bm25_index(texts:list[str], k1:float=1.5, b:float=0.75)->dict:
    n=len(texts)
    lengths=[]
    postings=defaultdict(dict)
    df=Counter()
    for doc_id,text in enumerate(texts):
        counts=Counter(tokenize(text))
        lengths.append(sum(counts.values()))
        for term,tf in counts.items():
            postings[term][doc_id]=tf
            df[term]+=1
    avg_len=(sum(lengths)/n) if n else 1.0
    idf={term:math.log(1.0+(n-f+0.5)/(f+0.5)) for term,f in df.items()}
    return {"postings":dict(postings),"doc_lengths":lengths,"idf":idf,"avg_doc_len":avg_len,"k1":k1,"b":b,"document_count":n}

print("Loading documents from ChromaDB...")

if not os.path.exists(CHROMA_PATH):
    raise RuntimeError(
        f"ChromaDB not found: {CHROMA_PATH}. "
        "Run pdf_to_chunks.py first."
    )

db=Chroma(persist_directory=CHROMA_PATH)

data=db.get()

texts=data.get("documents") or []
meta=data.get("metadatas") or []
ids=data.get("ids") or []

if not texts:
    raise RuntimeError(
        "ChromaDB is empty. Run pdf_to_chunks.py first."
    )

if len(texts)!=len(meta):
    raise RuntimeError(
        f"ChromaDB data mismatch: {len(texts)} documents but "
        f"{len(meta)} metadata records."
    )

if ids and len(ids)!=len(texts):
    raise RuntimeError(
        f"ChromaDB ID mismatch: {len(texts)} documents but "
        f"{len(ids)} IDs."
    )

if not ids:
    ids=[f"chunk-{i:05d}" for i in range(len(texts))]

print(f"{len(texts)} chunks loaded.")
print(f"{len(meta)} metadata records loaded.")
print(f"{len(ids)} chunk IDs loaded.")

enriched=[]
normalized_meta=[]

for index,(text,metadata,chunk_id) in enumerate(zip(texts,meta,ids)):
    metadata=dict(metadata or {})

    # Preserve a stable chunk identifier for later retrieval/RRF work.
    metadata["chunk_id"]=str(chunk_id)

    parts=[]

    if metadata.get("chapter"):
        parts.append(f"Chapter {metadata['chapter']}")

    if metadata.get("article"):
        parts.append(f"Article {metadata['article']}")

    if metadata.get("section"):
        parts.append(f"Section {metadata['section']}")

    if metadata.get("heading"):
        parts.append(metadata["heading"])

    # Preserve the improved page range generated by pdf_to_chunks.py.
    page_start=metadata.get("page_start")
    page_end=metadata.get("page_end")

    if page_start is not None and page_end is not None:
        if str(page_start)==str(page_end):
            parts.append(f"Page {page_start}")
        else:
            parts.append(f"Pages {page_start}-{page_end}")
    elif metadata.get("page"):
        parts.append(f"Page {metadata['page']}")

    prefix=" ".join(parts)
    enriched.append(
        (prefix+" "+(text or "")).strip()
    )
    normalized_meta.append(metadata)

meta=normalized_meta

print("Building true BM25 index...")
bm25=build_bm25_index(enriched)

if bm25.get("document_count")!=len(texts):
    raise RuntimeError(
        "BM25 document count does not match Chroma chunk count."
    )

out={
    "texts":texts,
    "enriched":enriched,
    "metadatas":meta,
    "ids":ids,
    "bm25":bm25,
    "version":"4.1-bm25"
}

with open(OUT_PATH,"wb") as f:
    pickle.dump(
        out,
        f,
        protocol=pickle.HIGHEST_PROTOCOL
    )

print(f"Hybrid model saved -> {OUT_PATH}")
print(
    f"Chunks: {len(texts)} | "
    f"Terms: {len(bm25['idf']):,} | "
    f"BM25 docs: {bm25['document_count']}"
)
print("Consistency check: Chroma chunks, metadata, IDs, and BM25 are aligned.")